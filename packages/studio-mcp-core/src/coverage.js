// Renders mcp/COVERAGE.md from the studio manifest and the live smoke results. Pure, so it is unit-tested.
// A studio is only marked ✔ when every model kind and every custom tool it relies on passed in a live (not dry) run.

/** Live column for one studio. `results` is the smoke report's results array. */
export function liveStatus(entry, results, customToolNames, date) {
  const byId = new Map((results || []).map((r) => [r.id, r]));
  const needed = [
    ...(entry.kinds || []).map((k) => `kind:${k}`),
    ...(entry.tools || []).filter((t) => customToolNames.has(t)).map((t) => `tool:${t}`),
  ];
  if (!needed.length) return 'no live check defined';
  const found = needed.map((id) => byId.get(id));
  if (found.every((r) => !r)) return 'not run';
  const failed = needed.filter((id) => byId.get(id)?.status === 'fail');
  if (failed.length) return `✘ ${failed.join(', ')}: ${String(byId.get(failed[0]).error || 'failed').replace(/\|/g, '/').slice(0, 120)}`;
  const passed = found.filter((r) => r?.status === 'pass').length;
  if (passed === needed.length) return `✔ ${date}`;
  const why = needed.filter((id) => byId.get(id)?.status !== 'pass').map((id) => `${id} ${byId.get(id)?.status || 'not run'}`).join('; ');
  return `partial ${passed}/${needed.length} (${why})`.slice(0, 200);
}

export function renderCoverage({ manifest, report, customToolNames, brandName = 'MCP' }) {
  const live = report && !report.dryRun ? report : null;
  const date = live?.generatedAt?.slice(0, 10);
  const rows = [
    ...Object.entries(manifest.supported).map(([s, v]) => `| \`${s}\` | supported | ${v.tools.map((t) => `\`${t}\``).join(', ')}${v.note ? ` (${String(v.note).replace(/\|/g, '/')})` : ''} | ${live ? liveStatus(v, live.results, customToolNames, date) : 'not run'} |`),
    ...Object.entries(manifest.unsupported).map(([s, why]) => `| \`${s}\` | not exposed | ${String(why).replace(/\|/g, '/')} | n/a |`),
  ];
  const neg = (live?.results || []).filter((r) => r.id.startsWith('neg:'));
  const negRows = neg.map((r) => `| ${r.id.slice(4)} | ${r.status === 'pass' ? '✔' : r.status === 'skipped' ? `skipped: ${r.reason}` : `✘ ${String(r.error || '').replace(/\|/g, '/')}`} |`);
  return `# ${brandName} MCP coverage

Generated by \`npm run mcp:coverage\` from \`mcp/studios.json\` and \`mcp/smoke-results.json\`. Offline checks (every studio classified, tools exist, request parity with the app's own code) run in \`npm run test:mcp\`.
The Live column comes from the smoke run against a deployed gateway with a real key (\`npm run mcp:smoke\`). It says "not run" until that has happened; dry runs never count.

${live ? `Last live run: ${live.generatedAt} against ${live.gateway}, estimated spend ~$${live.spentEstimateUsd}. Status route verb accepted upstream: ${live.pollProbe?.verb ?? 'not determined'}.` : 'No live run recorded yet.'}

${Object.keys(manifest.supported).length} supported, ${Object.keys(manifest.unsupported).length} not exposed.

| Studio | Status | Tools / reason | Live |
|---|---|---|---|
${rows.join('\n')}
${negRows.length ? `\n## Gateway checks (no spend)\n\n| Check | Result |\n|---|---|\n${negRows.join('\n')}\n` : ''}`;
}
