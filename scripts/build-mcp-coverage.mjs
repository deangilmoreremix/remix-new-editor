// Writes mcp/COVERAGE.md from mcp/studios.json: one row per studio with its tools or the reason it is not exposed.
// The "Live" column is filled by hand after running the live smoke matrix against a deployed gateway; it is preserved on regeneration.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const root = new URL('../mcp/', import.meta.url);
const { supported, unsupported } = JSON.parse(readFileSync(new URL('studios.json', root), 'utf8'));
const outPath = new URL('COVERAGE.md', root);

const prior = {};
if (existsSync(outPath)) {
  for (const line of readFileSync(outPath, 'utf8').split('\n')) {
    const m = /^\| `([^`]+)` \|.*\| ([^|]*) \|$/.exec(line);
    if (m) prior[m[1]] = m[2].trim();
  }
}

const rows = [
  ...Object.entries(supported).map(([s, v]) => `| \`${s}\` | supported | ${v.tools.map((t) => `\`${t}\``).join(', ')} | ${prior[s] || 'not run'} |`),
  ...Object.entries(unsupported).map(([s, why]) => `| \`${s}\` | not exposed | ${why.replace(/\|/g, '/')} | n/a |`),
];
const md = `# MCP coverage

Generated by \`npm run mcp:coverage\` from \`mcp/studios.json\`. Offline checks (every studio classified, tools exist, request parity with the app's own code) run in \`npm run test:mcp\`.
The Live column records the smoke run against a deployed gateway with a real key. It has not been run unless it says so.

${Object.keys(supported).length} supported, ${Object.keys(unsupported).length} not exposed.

| Studio | Status | Tools / reason | Live |
|---|---|---|---|
${rows.join('\n')}
`;
writeFileSync(outPath, md);
console.log(`mcp/COVERAGE.md: ${Object.keys(supported).length} supported, ${Object.keys(unsupported).length} not exposed`);
