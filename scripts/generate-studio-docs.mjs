#!/usr/bin/env node
// Keeps the written docs in step with the studios the app actually ships.
//
// Source of truth: the studio guides (src/data/askKb/*.json -> buildGuides), the route
// table (src/lib/router.js `pageLoaders`) and the folders under apps/.
//
// Writes (default):
//   README.md                      block between <!-- STUDIO-CATALOG:START/END -->
//   docs/STUDIOS_AND_PAGES.md      block between <!-- STUDIO-CATALOG:START/END -->
//   docs/STUDIO_FEATURE_CATALOG.md whole file (every studio, every feature)
// Checks (always, and the only thing `--check` does; it writes nothing and exits 1 on a problem):
//   - the three files above match what the guides say now
//   - every route in `pageLoaders` is a guide route or is listed in docs/STUDIOS_AND_PAGES.md
//   - every folder under apps/ is named in README.md
//
// Usage: node scripts/generate-studio-docs.mjs [--check]     (npm run docs:studios / npm run check:docs)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildGuides, groupByCategory } from '../src/data/studioGuides.core.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const readJson = (p) => JSON.parse(read(p));

// ---- load the guides (same inputs as scripts/build-studio-guides.mjs) ----
const kbDir = path.join(root, 'src/data/askKb');
const kb = {};
for (const f of fs.readdirSync(kbDir)) {
  if (f.endsWith('.json') && !f.startsWith('_')) kb[f.slice(0, -5)] = JSON.parse(fs.readFileSync(path.join(kbDir, f), 'utf8'));
}
const guides = buildGuides(kb, readJson('src/data/guideScreenshots.json'), {}, readJson('src/data/guideVideos.json'), readJson('src/data/muapiStudioAppsMap.json'));
const groups = groupByCategory(guides);
const featureTotal = guides.reduce((n, g) => n + g.features.length, 0);
const shotTotal = guides.reduce((n, g) => n + g.features.filter((f) => f.hasOwnScreenshot).length, 0);

// ---- rendering helpers ----
const cell = (s) => String(s ?? '').replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
const clip = (s, n) => { const t = cell(s); return t.length > n ? `${t.slice(0, n - 1).trimEnd()}…` : t; };
const firstSentence = (s, n = 220) => {
  const t = cell(s);
  const m = t.match(/^.*?[.!?](?=\s|$)/);
  return clip(m ? m[0] : t, n);
};
const guideUrl = (g) => `/studios/${g.slug}`;
const shots = (g) => g.features.filter((f) => f.hasOwnScreenshot).length;

function readmeBlock() {
  const out = [
    `**${guides.length} studio guides and ${featureTotal} documented features.** Every studio below has a public guide at \`/studios/<slug>\` (hub: \`/studios\`). The full feature-by-feature list is [docs/STUDIO_FEATURE_CATALOG.md](docs/STUDIO_FEATURE_CATALOG.md); the route map is [docs/STUDIOS_AND_PAGES.md](docs/STUDIOS_AND_PAGES.md).`,
    '',
    '_This block is generated by `npm run docs:studios` from the studio guides. Do not edit it by hand._',
  ];
  for (const c of groups) {
    out.push('', `#### ${c.title}`, '', `_${c.blurb}_`, '', '| Studio | Route | Features | What it does |', '|---|---|---|---|');
    for (const g of c.guides) out.push(`| [${cell(g.name)}](${guideUrl(g)}) | \`#/${g.route}\` | ${g.features.length} | ${clip(g.shortDescription, 200)} |`);
  }
  return out.join('\n');
}

function pagesBlock() {
  const out = [
    `**${guides.length} guides, ${featureTotal} features, ${shotTotal} with their own screenshot.** Guides hub: https://smartvid.app/studios`,
    '',
    '_This block is generated by `npm run docs:studios`. Edit the studio guides (src/data/askKb), not this table._',
    '',
    '## Studios with a feature guide',
  ];
  for (const c of groups) {
    out.push('', `### ${c.title}`, '', '| Studio | App route | Guide | Features | Own screenshots |', '|---|---|---|---|---|');
    for (const g of c.guides) {
      const s = shots(g);
      out.push(`| ${cell(g.name)} | #/${g.route} | ${guideUrl(g)} | ${g.features.length} | ${s === g.features.length ? s : `${s} (rest use the studio thumbnail)`} |`);
    }
  }
  return out.join('\n');
}

function catalogFile() {
  const out = [
    '# Studio feature catalog',
    '',
    `Every studio in the SmartVideo app and every feature its guide documents: **${guides.length} studios, ${featureTotal} features**.`,
    '',
    '> Generated by `npm run docs:studios` from the studio guides (`src/data/askKb/*.json`). Do not edit by hand: change the guide, then re-run the script.',
    '> Route map and non-studio pages: [STUDIOS_AND_PAGES.md](STUDIOS_AND_PAGES.md).',
    '',
    '## Contents',
    '',
  ];
  for (const c of groups) out.push(`- **${c.title}**: ${c.guides.map((g) => `[${cell(g.name)}](#${anchor(g.name)})`).join(', ')}`);
  for (const c of groups) {
    out.push('', `## ${c.title}`);
    for (const g of c.guides) {
      out.push('', `### ${cell(g.name)}`, '', `Route \`#/${g.route}\` · public guide \`${guideUrl(g)}\` · ${g.features.length} features`, '', cell(g.shortDescription));
      if (g.bestFor) out.push('', `**Best for:** ${clip(g.bestFor, 400)}`);
      out.push('', '| Feature | What it does |', '|---|---|');
      for (const f of g.features) out.push(`| ${cell(f.name)} | ${clip(f.definition || f.whyToUse, 260)} |`);
    }
  }
  return `${out.join('\n')}\n`;
}
// GitHub heading anchor: lowercase, drop punctuation, spaces to hyphens.
function anchor(name) {
  return cell(name).toLowerCase().replace(/[^\p{L}\p{N}\s-]/gu, '').replace(/\s/g, '-');
}

// ---- marker blocks ----
const START = '<!-- STUDIO-CATALOG:START -->';
const END = '<!-- STUDIO-CATALOG:END -->';
function withBlock(text, body, file) {
  const a = text.indexOf(START);
  const b = text.indexOf(END);
  if (a === -1 || b === -1 || b < a) throw new Error(`${file}: missing ${START} / ${END} markers`);
  return `${text.slice(0, a + START.length)}\n${body}\n${text.slice(b)}`;
}

const targets = [
  { file: 'README.md', next: (t) => withBlock(t, readmeBlock(), 'README.md') },
  { file: 'docs/STUDIOS_AND_PAGES.md', next: (t) => withBlock(t, pagesBlock(), 'docs/STUDIOS_AND_PAGES.md') },
  { file: 'docs/STUDIO_FEATURE_CATALOG.md', next: () => catalogFile(), optional: true },
];

const problems = [];
let wrote = 0;
for (const t of targets) {
  const abs = path.join(root, t.file);
  const current = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : '';
  const wanted = t.next(current);
  if (wanted === current) continue;
  if (check) problems.push(`${t.file} is out of date`);
  else { fs.writeFileSync(abs, wanted); wrote += 1; console.log(`[docs:studios] wrote ${t.file}`); }
}

// ---- coverage: routes and apps ----
const router = read('src/lib/router.js');
const loaders = router.match(/const pageLoaders = (\{[\s\S]*?\n\});/);
if (!loaders) problems.push('src/lib/router.js: could not find the pageLoaders table');
else {
  const keys = new Set([...loaders[1].matchAll(/^\s*['"]?([\w\-/]+)['"]?\s*:\s*(?:\(\)|async)/gm)].map((m) => m[1]));
  const guideRoutes = new Set(guides.map((g) => g.route));
  const pagesDoc = read('docs/STUDIOS_AND_PAGES.md');
  const documented = new Set([...pagesDoc.matchAll(/#\/([\w\-/<>]+)/g)].map((m) => m[1]));
  // A sub-route (smartwarmupai/inbox) is covered by its parent; a parent is covered by a documented sub-route.
  const covered = (k) => guideRoutes.has(k) || documented.has(k) || [...documented].some((d) => d.startsWith(`${k}/`))
    || (k.includes('/') && covered(k.slice(0, k.lastIndexOf('/'))));
  for (const k of [...keys].sort()) {
    if (!covered(k)) problems.push(`route #/${k} is in src/lib/router.js but is not in docs/STUDIOS_AND_PAGES.md: add a studio guide (src/data/askKb/${k}.json) or a row under "Other app routes"`);
  }
}
const readme = read('README.md');
for (const d of fs.readdirSync(path.join(root, 'apps'), { withFileTypes: true })) {
  if (d.isDirectory() && !readme.includes(`apps/${d.name}`)) problems.push(`apps/${d.name} is not mentioned in README.md: add it to the "Bundled apps" table`);
}

if (problems.length) {
  console.error(`[docs:studios] ${problems.length} problem(s):\n- ${problems.join('\n- ')}`);
  console.error(check ? '\nFix: run `npm run docs:studios`, then add anything it cannot generate by hand (see CLAUDE.md, "Keep the docs in step").' : '');
  process.exit(1);
}
console.log(check ? `[docs:studios] up to date (${guides.length} studios, ${featureTotal} features)` : `[docs:studios] ${wrote} file(s) updated (${guides.length} studios, ${featureTotal} features)`);
