#!/usr/bin/env node
// Builds the Warmbly Studio guide for the in-app help assistant from Warmbly's own feature guides
// (warmbly/docs/content/docs/guides/*.mdx). Nothing is written by hand: titles, descriptions, intros and
// numbered steps come straight from those pages, so re-run it after updating the warmbly/ copy.
//
//   node scripts/build-warmbly-guide.mjs            write the guide
//   node scripts/build-warmbly-guide.mjs --check    exit 1 if the committed guide is stale
//
// Target is detected from the repo: src/data/askKb/ (remix-new-editor) or src/data/studioKnowledgeBase.json (OpenHiggsBolt).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DOCS = path.join(ROOT, 'warmbly/docs/content/docs/guides');
const CHECK = process.argv.includes('--check');

const clean = (s) => String(s)
  .replace(/^import .*$/gm, '').replace(/<!--[\s\S]*?-->/g, '')
  .replace(/```[\s\S]*?```/g, '').replace(/!\[[^\]]*\]\([^)]*\)/g, '')
  .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1').replace(/<\/?[A-Za-z][^>]*>/g, '')
  .replace(/\*\*([^*]+)\*\*/g, '$1').replace(/(?<![\w*])\*([^*\n]+)\*(?![\w*])/g, '$1').replace(/`([^`]+)`/g, '$1')
  .replace(/^#{1,6}\s+/gm, '').replace(/^\s*[-*]\s+/gm, '').replace(/\|[-:| ]+\|/g, ' ')
  .replace(/\s+/g, ' ').replace(/\s*More about [A-Za-z ,&-]+$/, '').trim();

function parse(file) {
  const raw = fs.readFileSync(file, 'utf8');
  const fm = raw.match(/^---\n([\s\S]*?)\n---\n/);
  const get = (k) => (fm?.[1].match(new RegExp(`^${k}:\\s*(.*)$`, 'm'))?.[1] || '').replace(/^["']|["']$/g, '');
  const body = fm ? raw.slice(fm[0].length) : raw;
  const intro = clean(body.split(/\n##\s|<Steps>/)[0]);
  const steps = [...body.matchAll(/<Step>([\s\S]*?)<\/Step>/g)].map((m) => {
    const t = m[1].trim(); const h = t.match(/^#{2,4}\s+(.+)$/m);
    const text = clean(t); return h && !text.startsWith(clean(h[1]) + ':') ? text.replace(clean(h[1]), clean(h[1]) + ':') : text;
  }).filter(Boolean);
  const headings = [...body.matchAll(/^##\s+(.+)$/gm)].map((m) => clean(m[1])).filter(Boolean);
  return { title: get('title'), description: get('description'), intro, steps, headings };
}

const meta = JSON.parse(fs.readFileSync(path.join(DOCS, 'meta.json'), 'utf8'));
let section = ''; const guides = [];
for (const p of meta.pages) {
  if (p.startsWith('---')) { section = p.replace(/-/g, ' ').trim(); continue; }
  const file = path.join(DOCS, `${p}.mdx`); if (!fs.existsSync(file)) continue;
  guides.push({ slug: p, section: section || 'Start', ...parse(file) });
}
const start = guides.find((g) => g.slug === 'index');
const features = guides.filter((g) => g.slug !== 'index');
const sections = [...new Set(features.map((g) => g.section))];
const cap = (s, n) => (s.length > n ? s.slice(0, n - 1).replace(/\s+\S*$/, '') + '…' : s);

const common = {
  description: `Warmbly Studio is the open-source Warmbly platform for B2B cold email and mailbox warmup, open inside the app as a studio. ${start.intro}`,
  shortDescription: 'Cold email campaigns, mailbox warmup, a shared inbox and a CRM, from the mailboxes you own.',
  keyFeatures: features.map((g) => `${g.title}: ${g.description}`),
  featureExplanations: features.map((g) => ({ feature: g.title, explanation: cap(`${g.description} ${g.intro}`.trim(), 700) })),
  howToSteps: start.steps,
  exampleWorkflows: features.filter((g) => g.steps.length >= 3).map((g) => ({ title: g.title, steps: g.steps.map((s) => cap(s, 500)) })),
  sections: sections.map((s) => ({ section: s, guides: features.filter((g) => g.section === s).map((g) => g.title) })),
  sourceFiles: ['warmbly/docs/content/docs/guides/*.mdx', 'warmbly/docs/content/docs/guides/meta.json', 'warmbly/web/src/app/app'],
};
const source = `Generated by scripts/build-warmbly-guide.mjs from ${features.length} Warmbly feature guides.`;

function write(file, content) {
  const next = JSON.stringify(content, null, 2) + '\n';
  if (CHECK) { if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== next) { console.error(`stale: ${path.relative(ROOT, file)} (run node scripts/build-warmbly-guide.mjs)`); process.exit(1); } return; }
  fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, next); console.log('wrote', path.relative(ROOT, file));
}

const askKb = path.join(ROOT, 'src/data/askKb');
const studioKb = path.join(ROOT, 'src/data/studioKnowledgeBase.json');
if (fs.existsSync(askKb)) {
  const steps = common.howToSteps;
  write(path.join(askKb, 'warmbly.json'), {
    id: 'warmbly', name: 'Warmbly Studio', route: '#/warmbly', ...common,
    fullDescription: `${common.description} ${features.length} feature guides cover: ${sections.join('; ')}.`,
    bestFor: 'Teams that send B2B cold email from their own mailboxes and want warmup, campaigns, one inbox and a CRM in one place.',
    howToUse: steps.map((s, i) => `${i + 1}. ${s}`).join(' '),
    gettingStarted: steps,
    relatedStudios: ['leadfinder', 'personalizer', 'video-pages'],
    notConfirmed: ['Which features are available depends on the connected Warmbly backend; these guides are Warmbly\'s own how-to guides.'],
    sourceFiles: common.sourceFiles,
    verification: { status: 'docs-derived', evidence: source },
  });
} else if (fs.existsSync(studioKb)) {
  const kb = JSON.parse(fs.readFileSync(studioKb, 'utf8'));
  const entry = {
    id: 'warmbly', name: 'Warmbly Studio', route: '/studio/warmbly', ...common,
    fullDescription: `${common.description} ${features.length} feature guides cover: ${sections.join('; ')}.`,
    bestFor: 'Teams that send B2B cold email from their own mailboxes and want warmup, campaigns, one inbox and a CRM in one place.',
    howToUse: `Open Warmbly Studio at /studio/warmbly. ${common.howToSteps.map((s, i) => `${i + 1}. ${s}`).join(' ')}`,
    inputs: ['mailboxes you own', 'contacts', 'campaign sequences'], requiredInputs: ['a connected mailbox'], optionalInputs: ['contacts', 'sending domains', 'integrations'],
    outputs: ['sent campaigns', 'replies in one inbox', 'deliverability and analytics reports'],
    limitations: ['Needs the Warmbly backend connected'],
    relatedStudios: ['video-pages', 'go-ai-viral'],
    verification: { status: 'verified', evidence: source, verifiedAt: new Date().toISOString().slice(0, 10) },
  };
  const i = kb.studios.findIndex((s) => s.id === 'warmbly');
  if (CHECK) { const cur = kb.studios[i]; const a = JSON.stringify({ ...cur, verification: { ...cur?.verification, verifiedAt: '' } }); const b = JSON.stringify({ ...entry, verification: { ...entry.verification, verifiedAt: '' } }); if (a !== b) { console.error('stale: studioKnowledgeBase.json warmbly entry'); process.exit(1); } process.exit(0); }
  if (i >= 0) kb.studios[i] = entry; else kb.studios.push(entry);
  kb.meta.totalStudios = kb.studios.length;
  fs.writeFileSync(studioKb, JSON.stringify(kb, null, 2) + '\n'); console.log('updated', path.relative(ROOT, studioKb), `(${kb.studios.length} studios)`);
} else { console.error('No help knowledge base found in this repo.'); process.exit(1); }
