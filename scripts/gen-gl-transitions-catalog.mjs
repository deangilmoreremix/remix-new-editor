#!/usr/bin/env node
// Generates the vendored gl-transitions catalog from an upstream checkout.
//   node scripts/gen-gl-transitions-catalog.mjs <path-to-gl-transitions-checkout> [--out <dir>]
// Outputs (all deterministic, no timestamps):
//   src/openchatcut/gl/glt/catalog.generated.ts        curated, vendored shaders: metadata + verbatim upstream source
//   src/openchatcut/gl/glt/upstream-index.generated.json  all upstream transitions: licence/author + vendored / excluded reason
//   src/openchatcut/gl/glt/THIRD_PARTY.md              per-shader author + licence notice
// Upstream is untrusted input: files are only read and parsed as text, never executed.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { parseTransition, kebab } from './lib/glt-parse.mjs';
import { CURATED, EXCLUDED_REASONS } from './lib/glt-curated.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const oi = args.indexOf('--out');
const OUT = oi >= 0 ? path.resolve(args[oi + 1]) : path.join(ROOT, 'src/openchatcut/gl/glt');
if (oi >= 0) args.splice(oi, 2);
fs.mkdirSync(OUT, { recursive: true });
const up = args[0] || process.env.GLT_UPSTREAM;
if (!up) { console.error('usage: gen-gl-transitions-catalog.mjs <gl-transitions checkout>'); process.exit(2); }
const dir = path.join(up, 'transitions');
const commit = execFileSync('git', ['-C', up, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();

const files = fs.readdirSync(dir).filter((f) => f.endsWith('.glsl')).sort();
const index = [];
const vendored = [];
const curatedNames = new Map(Object.entries(CURATED).flatMap(([cat, names]) => names.map((n) => [n, cat])));
for (const n of curatedNames.keys()) if (!files.includes(`${n}.glsl`)) throw new Error(`curated name not upstream: ${n}`);
for (const f of files) {
  const name = f.replace(/\.glsl$/, '');
  const src = fs.readFileSync(path.join(dir, f), 'utf8');
  const p = parseTransition(src);
  const cat = curatedNames.get(name);
  const row = { name, author: p.header.author, license: p.header.license, paramCount: p.params.length, textures: p.textures, vendored: !!cat };
  if (!cat) row.excluded = EXCLUDED_REASONS[name] || (p.textures.length ? 'needs an extra texture' : 'not in curated set');
  index.push(row);
  if (!cat) continue;
  if (p.errors.length) throw new Error(`${name}: ${p.errors.join('; ')}`);
  if (p.textures.length) throw new Error(`${name}: extra textures are not supported`);
  vendored.push({ id: `glt-${kebab(name)}`, name, category: cat, author: p.header.author, license: p.header.license, description: p.header.description, tags: p.header.tags, params: p.params, glsl: src });
}
vendored.sort((a, b) => a.id.localeCompare(b.id));

const header = `// GENERATED by scripts/gen-gl-transitions-catalog.mjs from gl-transitions@${commit} — do not edit by hand.
// Each \`glsl\` is the verbatim upstream file (per-file licence header kept). See THIRD_PARTY.md.
/* eslint-disable */
`;
const ts = `${header}export interface GltParam { name: string; type: 'float' | 'int' | 'bool' | 'vec2' | 'vec3' | 'vec4' | 'ivec2'; default: number | boolean | number[]; min?: number; max?: number; step?: number; color?: boolean; description?: string }
export interface GltEntry { id: string; name: string; category: string; author: string; license: string; description: string; tags: string[]; params: GltParam[]; glsl: string }
export const GLT_UPSTREAM = { repo: 'https://github.com/gl-transitions/gl-transitions', commit: ${JSON.stringify(commit)} } as const;
export const GLT_CATALOG: readonly GltEntry[] = ${JSON.stringify(vendored, null, 1)};
`;
fs.writeFileSync(path.join(OUT, 'catalog.generated.ts'), ts);
fs.writeFileSync(path.join(OUT, 'upstream-index.generated.json'), JSON.stringify({ commit, transitions: index }, null, 1) + '\n');

const rootLicense = fs.readFileSync(path.join(up, 'LICENSE'), 'utf8').trim();
const md = [
  '# Third-party notice: gl-transitions',
  '',
  `Shaders in \`catalog.generated.ts\` are vendored from https://github.com/gl-transitions/gl-transitions at commit \`${commit}\`.`,
  'Each shader keeps its upstream licence header (verbatim file contents). Author and licence are per shader, as stated in each file header.',
  'Shaders are adapted at runtime only by wrapping (see `buildFrag.ts`); the shader text itself is not modified.',
  '',
  '## Repository licence',
  '',
  '```',
  rootLicense,
  '```',
  '',
  '## Vendored shaders',
  '',
  '| Id | Upstream name | Author | Licence |',
  '|---|---|---|---|',
  ...vendored.map((v) => `| ${v.id} | ${v.name} | ${v.author.replace(/\|/g, '/')} | ${v.license} |`),
  '',
  vendored.some((v) => /BSD/.test(v.license)) ? 'BSD-licensed shaders keep their copyright/disclaimer in the shader header; redistribution must retain it.\n' : '',
].join('\n');
fs.writeFileSync(path.join(OUT, 'THIRD_PARTY.md'), md);
console.log(`vendored ${vendored.length} of ${files.length} shaders @ ${commit}`);
