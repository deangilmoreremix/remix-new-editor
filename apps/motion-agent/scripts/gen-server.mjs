// Bundles the Video Agent server route (server/generate-route.ts, ported from the
// template's Next.js API route) together with the template's skill guides (src/skills:
// .md guidance + code examples) into one ES module the Netlify function imports. The
// function bundler can't load .md files or the "@/" alias, so this runs ahead of time.
// Output is committed; re-run after changing server/ or src/skills or src/examples:
//   node apps/motion-agent/scripts/gen-server.mjs
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const app = fileURLToPath(new URL("..", import.meta.url));
const out = path.join(app, "../../netlify/functions/_shared/videoAgentGenerate.generated.mjs");

await build({
  entryPoints: [path.join(app, "server/generate-route.ts")],
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  outfile: out,
  loader: { ".md": "text" },
  alias: { "@": path.join(app, "src") },
  // Resolved from the repo root node_modules when Netlify bundles the function.
  external: ["ai", "@ai-sdk/openai", "zod"],
  banner: { js: "// GENERATED by apps/motion-agent/scripts/gen-server.mjs from apps/motion-agent/server/generate-route.ts — do not edit.\n/* eslint-disable */" },
  logLevel: "warning",
});
console.log("wrote", path.relative(process.cwd(), out));
