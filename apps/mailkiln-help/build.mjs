const here = path.dirname(fileURLToPath(import.meta.url));
const brand = JSON.parse(fs.readFileSync(path.join(here, "../mailkiln-brand/brand.json"), "utf8"));
const HELP = process.env.HELP_BASE || brand.paths.help; // absolute base of the site, trailing slash
const OUT = path.resolve(process.argv[2] || path.join(here, "dist"));
const CONTENT = path.join(here, "content/docs");
const UP = brand.upstream.name;
const NAME = brand.name;

// ---------- brand rules (prose only; code, commands, settings and API paths are never touched) ----------
export const rebrand = (s) => String(s ?? "").replace(new RegExp(`\\b${UP}\\b`, "g"), NAME);
const upstreamHost = /^https?:\/\/([a-z0-9-]+\.)*warmbly\.com(?=[/:?#]|$)/i;
const dropHosts = [/^https?:\/\/(www\.)?x\.com\/WarmblyHQ/i, /^https?:\/\/github\.com\/sponsors\/warmbly/i, /^https?:\/\/dc\.warmbly\.com/i];
const SECTIONS = ["guides", "learn", "api", "development", "contributing"];
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

// ---------- navigation from meta.json ----------
const readJSON = (f) => JSON.parse(fs.readFileSync(f, "utf8"));
const titleCase = (s) => s.replace(/[-_]/g, " ").replace(/^./, (c) => c.toUpperCase());

const pages = new Map(); // url ("guides/mailboxes/") -> page
function frontmatterOf(file) {
  const raw = fs.readFileSync(file, "utf8");
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?/);
  return { raw, fm: m ? YAML.parse(m[1]) ?? {} : {}, body: m ? raw.slice(m[0].length) : raw };
}
function walkDir(dir, rel = "") {
  const metaFile = path.join(dir, "meta.json");
  const meta = fs.existsSync(metaFile) ? readJSON(metaFile) : {};
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const files = new Map(entries.filter((e) => e.isFile() && /\.mdx?$/.test(e.name)).map((e) => [e.name.replace(/\.mdx?$/, ""), path.join(dir, e.name)]));
  const dirs = new Map(entries.filter((e) => e.isDirectory()).map((e) => [e.name, path.join(dir, e.name)]));
  const order = [];
  for (const p of meta.pages ?? []) order.push(p);
  for (const k of [...files.keys(), ...dirs.keys()].sort()) if (!order.includes(k)) order.push(k);
  const node = { title: meta.title ?? titleCase(path.basename(dir)), items: [] };
  for (const item of order) {
    if (item === "...") continue;
    const sep = item.match(/^---(.*)---$/);
    if (sep) { node.items.push({ separator: sep[1].trim() }); continue; }
    if (files.has(item)) {
      const { fm } = frontmatterOf(files.get(item));
      const url = (item === "index" ? rel : `${rel}${item}/`) || "";
      const page = { url, file: files.get(item), title: fm.title ?? titleCase(item), description: fm.description ?? "", index: item === "index" };
      pages.set(url, page); node.items.push({ page });
    } else if (dirs.has(item)) node.items.push({ group: walkDir(dirs.get(item), `${rel}${item}/`), url: `${rel}${item}/` });
  }
  return node;
}
const tree = {};
for (const s of SECTIONS.filter((x) => x !== "contributing")) tree[s] = walkDir(path.join(CONTENT, s), `${s}/`);

// "Developers & agents": the rebranded README, contributing guide, agent rules and skills (plain Markdown, generated by agent-docs.mjs).
function agentSection() {
  const dir = path.join(here, "agent");
  const node = { title: "Developers & agents", items: [] };
  if (!fs.existsSync(dir)) return node;
  const add = (rel, title, slug) => {
    const file = path.join(dir, rel); if (!fs.existsSync(file)) return;
    const { fm } = frontmatterOf(file); const url = `contributing/${slug}/`;
    const page = { url, file, md: true, title: fm.title ?? title, description: fm.description ? String(fm.description).replace(/\s+/g, " ").slice(0, 200) : "", index: slug === "overview" };
    pages.set(url, page); node.items.push({ page });
  };
  add("README.md", "Overview", "overview"); add("CONTRIBUTING.md", "Contributing", "contributing"); add("AGENTS.md", "Agent and contributor rules", "agent-rules");
  node.items.push({ separator: "Agent skills" });
  for (const s of fs.existsSync(path.join(dir, "skills")) ? fs.readdirSync(path.join(dir, "skills")).sort() : []) add(`skills/${s}/SKILL.md`, s, s);
  return node;
}
tree.contributing = agentSection();

function flatten(node, out = []) {
  for (const it of node.items) { if (it.page) out.push(it.page); else if (it.group) flatten(it.group, out); }
  return out;
}
const order = SECTIONS.flatMap((s) => flatten(tree[s]));

// ---------- link rewriting ----------
const broken = [];
// Links that are already broken upstream, mapped to the page they meant.
const ALIASES = { "guides/unified-inbox/": "guides/unibox/" };
function resolveHref(href, fromUrl) {
  if (!href) return { href };
  if (dropHosts.some((r) => r.test(href))) return { drop: true };
  const docs = href.match(/^https?:\/\/docs\.warmbly\.com(\/[^?#]*)?([?#].*)?$/i);
  let target = docs ? docs[1] ?? "/" : href;
  const tail = docs ? docs[2] ?? "" : "";
  if (!docs && upstreamHost.test(href)) return { drop: true };
  if (/^(https?:|mailto:|tel:|#)/i.test(target)) return { href };
  const helpRoot = HELP.replace(/\/$/, "");
  if (target === helpRoot) target = "/"; else if (target.startsWith(HELP)) target = `/${target.slice(HELP.length)}`;
  let hash = ""; const hi = target.indexOf("#"); if (hi >= 0) { hash = target.slice(hi); target = target.slice(0, hi); }
  target = target.split("?")[0];
  let abs = target;
  if (!target.startsWith("/")) { const base = path.posix.join("/", fromUrl); abs = path.posix.normalize(path.posix.join(path.posix.dirname(base + "x"), target)); }
  abs = abs.replace(/\.mdx?$/, "").replace(/\/index$/, "");
  const key = abs.replace(/^\/+|\/+$/g, "");
  let url = key ? `${key}/` : "";
  if (ALIASES[url]) url = ALIASES[url];
  if (url === "" || pages.has(url) || SECTIONS.includes(key)) return { href: `${HELP}${SECTIONS.includes(key) ? tree[key].items.find((i) => i.page?.index)?.page.url ?? url : url}${hash || tail}` };
  if (/\.(png|jpe?g|webp|svg|gif|json|ya?ml)$/i.test(target)) return { href: `${HELP}${key}${hash}`, asset: true };
  broken.push(`${fromUrl} -> ${href}`);
  return { href: `${HELP}${url}${hash}` };
}

// ---------- mdast plugin: rebrand + links + headings ----------
function remarkBrand(ctx) {
  return (tree) => {
    const toc = []; const seen = new Map();
    visit(tree, (node, index, parent) => {
      if (node.type === "text") node.value = rebrand(node.value);
      if (node.type === "image") { node.alt = rebrand(node.alt); const r = resolveHref(node.url, ctx.url); if (r.href) node.url = r.href; }
      if (node.type === "link") {
        const r = resolveHref(node.url, ctx.url);
        if (r.drop && parent && typeof index === "number") { parent.children.splice(index, 1, ...node.children); return index; }
        if (r.href) node.url = r.href; if (node.title) node.title = rebrand(node.title);
      }
      if (node.type === "heading") {
        const text = toString(node); let id = text.toLowerCase().replace(/[^\p{L}\p{N}\s-]/gu, "").trim().replace(/\s+/g, "-") || "section";
        const n = seen.get(id) ?? 0; seen.set(id, n + 1); if (n) id += `-${n}`;
        node.data = { ...(node.data ?? {}), hProperties: { id } };
        if (node.depth === 2 || node.depth === 3) toc.push({ depth: node.depth, id, text: rebrand(text) });
      }
      if (node.type === "mdxJsxFlowElement" || node.type === "mdxJsxTextElement") {
        for (const a of node.attributes ?? []) if (a.type === "mdxJsxAttribute" && typeof a.value === "string") {
          if (a.name === "href") { const r = resolveHref(a.value, ctx.url); if (r.drop) { a.value = ""; node.__drop = true; } else if (r.href) a.value = r.href; }
          else if (a.name !== "src") a.value = rebrand(a.value);
          else { const r = resolveHref(a.value, ctx.url); if (r.href) a.value = r.href; }
        }
      }
      if (node.type === "mdxjsEsm" || node.type === "mdxFlowExpression" || node.type === "mdxTextExpression") { if (parent && typeof index === "number") { parent.children.splice(index, 1); return index; } }
    });
    ctx.toc = toc;
  };
}

// ---------- hast handlers for upstream's MDX components ----------
const attr = (node, name) => { const a = (node.attributes ?? []).find((x) => x.type === "mdxJsxAttribute" && x.name === name); return a && typeof a.value === "string" ? a.value : undefined; };
const el = (tagName, properties, children) => ({ type: "element", tagName, properties: properties ?? {}, children: children ?? [] });
const txt = (value) => ({ type: "text", value });
function jsxHandler(state, node) {
  const name = node.name; const kids = state.all(node);
  switch (name) {
    case "Callout": { const type = attr(node, "type") ?? "info"; const title = attr(node, "title");
      return el("aside", { className: ["callout", `callout-${type}`] }, [...(title ? [el("strong", { className: ["callout-title"] }, [txt(title)])] : []), ...kids]); }
    case "ShortVersion": return el("aside", { className: ["callout", "callout-info"] }, [el("strong", { className: ["callout-title"] }, [txt("Short version")]), ...kids]);
    case "Steps": return el("ol", { className: ["steps"] }, kids.filter((k) => k.type !== "text" || k.value.trim()));
    case "Step": return el("li", { className: ["step"] }, kids);
    case "Fold": return el("details", { className: ["fold"] }, [el("summary", {}, [txt(attr(node, "title") ?? "Details")]), ...kids]);
    case "Cards": return el("div", { className: ["cards"] }, kids.filter((k) => k.type !== "text" || k.value.trim()));
    case "Card": { const href = attr(node, "href"); const title = attr(node, "title"); const body = [el("strong", {}, [txt(title ?? "")]), ...kids];
      return href ? el("a", { className: ["card"], href }, body) : el("div", { className: ["card"] }, body); }
    case "Tabs": return el("div", { className: ["tabs"] }, kids.filter((k) => k.type !== "text" || k.value.trim()));
    case "TabsList": case "TabsTrigger": return { type: "text", value: "" };
    case "Tab": case "TabsContent": case "LangTab": return el("section", { className: ["tab"] }, [el("h4", { className: ["tab-title"] }, [txt(attr(node, "title") ?? attr(node, "label") ?? attr(node, "lang") ?? attr(node, "value") ?? "")]), ...kids]);
    case "Mermaid": return el("pre", { className: ["diagram"] }, [el("code", {}, [txt(attr(node, "chart") ?? "")])]);
    default:
      if (/^[a-z]/.test(name ?? "")) { const props = {}; for (const a of node.attributes ?? []) if (a.type === "mdxJsxAttribute" && typeof a.value === "string") props[a.name === "class" ? "className" : a.name] = a.value; return el(name, props, kids); }
      if (!name) return el("span", {}, kids); // fragment
      return el("div", { className: ["diagram-placeholder"] }, [txt(`Interactive illustration (${name}) is available in the full product documentation.`)]);
  }
}

function render(page) {
  const { body, fm } = frontmatterOf(page.file);
  const ctx = { url: page.url, toc: [] };
  const base = unified().use(remarkParse).use(remarkFrontmatter, ["yaml"]).use(remarkGfm);
  const processor = (page.md ? base : base.use(remarkMdx)).use(remarkBrand, ctx)
    .use(remarkRehype, { handlers: { mdxJsxFlowElement: jsxHandler, mdxJsxTextElement: jsxHandler }, passThrough: [] }).use(rehypeStringify, { allowDangerousHtml: false });
  const mdast = processor.parse(body);
  const html = processor.stringify(processor.runSync(mdast));
  const tree = (page.md ? unified().use(remarkParse).use(remarkFrontmatter, ["yaml"]).use(remarkGfm) : unified().use(remarkParse).use(remarkFrontmatter, ["yaml"]).use(remarkGfm).use(remarkMdx)).parse(body);
  // plain text for search (code excluded)
  const textOnly = []; visit(tree, (n) => { if (n.type === "code" || n.type === "inlineCode") return SKIP; if (n.type === "text") textOnly.push(n.value); });
  return { html, toc: ctx.toc, text: rebrand(textOnly.join(" ").replace(/\s+/g, " ")), fm };
}

// ---------- templates ----------
const navHtml = (section, currentUrl) => {
  const li = (it) => {
    if (it.separator !== undefined) return `<li class="sep">${esc(rebrand(it.separator))}</li>`;
    if (it.page) { const cur = it.page.url === currentUrl; return `<li><a href="${HELP}${it.page.url}"${cur ? ' aria-current="page"' : ""}>${esc(rebrand(it.page.title))}</a></li>`; }
    return `<li class="grp"><span>${esc(rebrand(it.group.title))}</span><ul>${it.group.items.map(li).join("")}</ul></li>`;
  };
  return `<ul>${tree[section].items.map(li).join("")}</ul>`;
};
const sectionOf = (url) => SECTIONS.find((s) => url.startsWith(`${s}/`)) ?? "guides";
const SECTION_LABEL = { guides: "Guides", learn: "Learn", api: "API", development: "Self-hosting & engineering", contributing: "Developers & agents" };

function shell({ title, description, section, url, body, toc = [], prev, next }) {
  const tabs = SECTIONS.map((s) => `<a href="${HELP}${(tree[s].items.find((i) => i.page?.index) ?? tree[s].items.find((i) => i.page))?.page.url ?? `${s}/`}"${s === section ? ' aria-current="true"' : ""}>${SECTION_LABEL[s]}</a>`).join("");
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(rebrand(title))} · ${NAME} Help</title><meta name="description" content="${esc(rebrand(description))}">
<link rel="stylesheet" href="${HELP}assets/help.css"><script defer src="${HELP}assets/help.js" data-base="${HELP}"></script></head>
<body><header class="top"><a class="brand" href="${HELP}">${NAME} <span>Help</span></a><nav class="sections">${tabs}</nav>
<div class="search"><input id="q" type="search" placeholder="Search the documentation…" aria-label="Search the documentation" autocomplete="off"><ul id="results" hidden></ul></div></header>
<div class="layout"><aside class="side"><button class="navtoggle" aria-expanded="false">Menu</button>${section ? navHtml(section, url) : ""}</aside>
<main><article>${url !== null ? `<h1>${esc(rebrand(title))}</h1>${description ? `<p class="lede">${esc(rebrand(description))}</p>` : ""}` : ""}${body}
<nav class="pager">${prev ? `<a rel="prev" href="${HELP}${prev.url}">← ${esc(rebrand(prev.title))}</a>` : "<span></span>"}${next ? `<a rel="next" href="${HELP}${next.url}">${esc(rebrand(next.title))} →</a>` : "<span></span>"}</nav></article>
<footer>${NAME} Help is based on the open-source ${UP} project (${brand.upstream.license}). <a href="${HELP}about/">About this documentation</a></footer></main>
<aside class="toc">${toc.length ? `<strong>On this page</strong><ul>${toc.map((t) => `<li class="d${t.depth}"><a href="#${t.id}">${esc(t.text)}</a></li>`).join("")}</ul>` : ""}</aside></div></body></html>`;
}

