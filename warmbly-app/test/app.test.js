import { test } from 'node:test';
import assert from 'node:assert/strict';
import { openDb } from '../src/db.js';
import { createApp } from '../src/server.js';

process.env.WARMBLY_SIMULATE = '1'; process.env.WARMBLY_IGNORE_WINDOW = '1';
test('campaign flow: launch, send, track, reply, unsubscribe', async () => {
  const app = createApp({ db: openDb(':memory:'), port: 0 });
  const port = await app.listen(); const u = `http://localhost:${port}`;
  const { token } = await (await fetch(u + '/api/login', { method: 'POST', body: JSON.stringify({ password: app.adminPw }) })).json();
  const api = async (m, p, b) => (await fetch(u + p, { method: m, headers: { authorization: 'Bearer ' + token }, body: b ? JSON.stringify(b) : undefined })).json();
  assert.equal((await fetch(u + '/api/contacts')).status, 401);
  const mb = (await api('POST', '/api/mailboxes', { email: 'me@x.com', min_gap_sec: 0 })).id;
  await api('POST', '/api/contacts', { contacts: [{ email: 'a@b.com', first_name: 'Ann' }, { email: 'c@d.com' }, { email: 'bad' }] });
  const id = (await api('POST', '/api/campaigns', { name: 'T', mailbox_ids: [mb], steps: [{ subject: 'Hi {{first_name|there}}', body: 'Hello <a href="https://e.com">x</a>' }, { delay_days: 2, subject: 'f', body: 'f' }] })).id;
  await api('PATCH', `/api/campaigns/${id}`, { status: 'active' });
  const r = await api('POST', '/api/tick');
  assert.equal(r.sent, 2);
  const c = (await api('GET', '/api/campaigns'))[0];
  assert.equal(c.sent, 2); assert.equal(c.enrolled, 2);
  await fetch(`${u}/t/o/1.gif`); const click = await fetch(`${u}/t/c/1?u=https://e.com`, { redirect: 'manual' });
  assert.equal(click.status, 302);
  await api('POST', '/api/replies', { contact_id: 1, body: 'interested' });
  assert.equal((await api('GET', '/api/inbox')).length, 1);
  await fetch(`${u}/u/2`);
  assert.equal((await api('GET', '/api/suppressions'))[0].email, 'c@d.com');
  const d = await api('GET', '/api/dashboard');
  assert.deepEqual([d.opens, d.clicks, d.replies, d.unsubscribes], [1, 1, 1, 1]);
  app.close();
});
