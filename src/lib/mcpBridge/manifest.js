// The tab tools every adapter offers, collected for mcp/bridge-tools.json. Built from the adapters' own definitions with inert stand-ins for
// the live editors, so this file only lists; it never re-describes a tool.
import { createAgentTools } from '../editor/agent/tools.js';
import { toBridgeTools } from '../editor/agent/bridgeTools.js';
import { createWorkbenchTools, WORKBENCH_NOT_EXPOSED } from './adapters/workbench.js';
import { createMotionDirectorTools, MOTION_DIRECTOR_NOT_EXPOSED } from './adapters/motionDirector.js';
import { createRenderQueueTools, RENDER_QUEUE_NOT_EXPOSED } from './adapters/renderQueue.js';
import { createBrandTools, BRAND_NOT_EXPOSED } from './adapters/brand.js';
import { createAppTools } from './adapters/app.js';

const inert = () => { throw new Error('manifest only'); };
const brandStub = new Proxy({}, { get: () => inert });

export const TIMELINE_NOT_EXPOSED = {
  timeline_export_video_to_disk: 'export_video renders in the browser; the file is saved by the page, not returned.',
};

export function adapterTools() {
  return {
    timeline: toBridgeTools(createAgentTools({ snapshot: () => ({ timelineSeconds: 0, playheadSec: 0, tracks: [] }), confirm: async () => false })),
    workbench: createWorkbenchTools({ rpc: { call: inert }, importAssets: inert }),
    motion_director: createMotionDirectorTools({ getState: inert, interpretAgentCommand: inert, applyAgentOps: inert, cards: {}, requestExport: inert }),
    render: createRenderQueueTools({ list: inert, enqueue: inert, remove: inert, process: inert }),
    brand: createBrandTools(brandStub),
    app: createAppTools({ getCurrentPage: inert, navigate: inert, isKnownPage: inert }),
  };
}

export const NOT_EXPOSED = {
  timeline: TIMELINE_NOT_EXPOSED,
  workbench: WORKBENCH_NOT_EXPOSED,
  motion_director: MOTION_DIRECTOR_NOT_EXPOSED,
  render: RENDER_QUEUE_NOT_EXPOSED,
  brand: BRAND_NOT_EXPOSED,
  cinegen: {
    cinegen_export: 'Desktop only: the CineGen web editor has no export host; export runs through the Electron app.',
    cinegen_extract_media: 'Desktop only: needs the Electron app\'s file access.',
    cinegen_web_host: 'The CineGen timeline\'s McpHost handlers (createMcpHandlers) bind to Electron IPC; there is no web host implementation in this app, so no cinegen_* tab tools are offered. Server-side CineGen actions (fill_gap, extend, element_create, shot_board) are covered by the cinegen gateway studio.',
  },
  video_agent: {
    video_agent_edit: 'The Video Agent runs in an iframe whose only protocol is auth in and exported video out; it has no call to read or change the animation it is making.',
  },
};

export function buildBridgeManifest() {
  const tools = adapterTools();
  return {
    note: 'Generated by `npm run mcp:bridge-manifest` from the adapters. Do not edit by hand; a test fails when this drifts.',
    studios: Object.fromEntries(Object.entries(tools).map(([studio, list]) => [studio, list.map((t) => ({ name: t.name, risk: t.risk, description: t.description, schema: t.schema }))])),
    notExposed: NOT_EXPOSED,
  };
}
