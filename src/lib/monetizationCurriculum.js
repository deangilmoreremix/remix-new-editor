export function getTrackById(id) {
  const result = CURRICULUM_TRACKS.find(t => t.id === id);
  if (!result) { console.warn(`Track not found: ${id}`); return null; }
  return result;
}

export function getModuleByTrackAndIndex(trackId, moduleIndex) {
  const track = getTrackById(trackId);
  if (!track) return null;
  return track.modules?.[moduleIndex] || null;
}

export function getLessonByTrackModuleLesson(trackId, moduleIndex, lessonIndex) {
  const track = getTrackById(trackId);
  if (!track) return null;
  // Lessons are in lessons_data array
  const allLessons = track.lessons_data || [];
  return allLessons[lessonIndex] || null;
}

export function searchTracks({ query = '', level = '' } = {}) {
  const q = query.toLowerCase().trim();
  return CURRICULUM_TRACKS.filter(t => {
    if (level && t.level !== level) return false;
    if (!q) return true;
    return t.title.toLowerCase().includes(q) ||
           t.description.toLowerCase().includes(q) ||
           (t.lessons_data || []).some(l =>
             l.title.toLowerCase().includes(q) ||
             l.problem.toLowerCase().includes(q) ||
             (l.concept || []).some(c => c.toLowerCase().includes(q))
           );
  });
}

export function getAllLessons() {
  const all = [];
  CURRICULUM_TRACKS.forEach(t => {
    (t.lessons_data || []).forEach(l => {
      all.push({ ...l, trackId: t.id, trackTitle: t.title });
    });
  });
  return all;
}

