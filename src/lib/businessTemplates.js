export function getTemplateById(id) { return BUSINESS_TEMPLATES.find(t => t.id === id); }
export function getTemplatesByCategory(category) { return BUSINESS_TEMPLATES.filter(t => t.category === category); }
export function getTemplatesByType(type) { return BUSINESS_TEMPLATES.filter(t => t.type === type); }
export function searchTemplates({ query = '', category = '' } = {}) {
  const q = query.toLowerCase().trim();
  return BUSINESS_TEMPLATES.filter(t => {
    if (category && t.category !== category) return false;
    if (!q) return true;
    return t.title.toLowerCase().includes(q) ||
           (t.description || '').toLowerCase().includes(q) ||
           (t.shortDescription || '').toLowerCase().includes(q) ||
           (t.framework || '').toLowerCase().includes(q);
  });
}
